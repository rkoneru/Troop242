/**
 * Helper: Get requirement count for a rank
 * @param rankIdx {number} Rank index (0-6)
 * @returns {number} Total requirements for that rank
 */
export function getRequirementCount(rankIdx) {
  if (rankIdx < 0 || rankIdx >= RANKS.length) return 0;
  return RANKS[rankIdx].requirements.length;
}
